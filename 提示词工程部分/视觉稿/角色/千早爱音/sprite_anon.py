def _norm(art):
    rows = [r.ljust(W, ".")[:W] for r in art]
    rows += ["." * W] * (H - len(rows))
    return rows[:H]


def render(art, scale=1):
    rows = _norm(art)
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            color = PALETTE.get(ch)
            if color:
                px[x, y] = color + (255,)
    if scale != 1:
        img = img.resize((W * scale, H * scale), Image.NEAREST)
    return img


def ruler(art):
    rows = _norm(art)
    print("     " + "".join(str(i % 10) for i in range(W)))
    print("     " + "-" * W)
    for y, r in enumerate(rows):
        print(f"{y:3d}  {r}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--outdir", default=".")
    ap.add_argument("--ruler", action="store_true")
    args = ap.parse_args()
    out = Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)

    if args.ruler:
        ruler(ART)

    fig = render(ART, 6)
    sheet = Image.new("RGB", (W * 6 + 40, H * 6 + 20), (22, 30, 41))
    sheet.paste(fig, (20, 10), fig)
    sheet.save(out / "anon_ascii.png")
    print(f"[ok] anon_ascii.png ({sheet.width}×{sheet.height})")


if __name__ == "__main__":
    main()
